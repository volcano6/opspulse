package server

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/volcano6/opspulse/internal/config"
	"github.com/volcano6/opspulse/internal/secret"
)

const (
	// MarkerBegin marks the start of Ops-managed configuration in ~/.ssh/config.
	MarkerBegin = "# >>> BEGIN OpsPulse Managed Hosts >>>"
	// MarkerEnd marks the end of Ops-managed configuration in ~/.ssh/config.
	MarkerEnd = "# <<< END OpsPulse Managed Hosts <<<"
)

// DefaultSSHConfigPath returns the canonical path to ~/.ssh/config.
func DefaultSSHConfigPath() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("determine user home directory: %w", err)
	}
	return filepath.Join(home, ".ssh", "config"), nil
}

// RenderSSHConfig renders the OpenSSH config block for the provided servers.
func RenderSSHConfig(servers []Server) string {
	var buf bytes.Buffer
	buf.WriteString(MarkerBegin + "\n")
	buf.WriteString("# Do not edit this section directly. Automatically generated by Ops (ops export ssh-config).\n\n")

	if len(servers) == 0 {
		buf.WriteString("# No managed hosts configured in Ops inventory.\n")
		buf.WriteString(MarkerEnd + "\n")
		return buf.String()
	}

	// Sort servers alphabetically by name for deterministic output
	sorted := make([]Server, len(servers))
	copy(sorted, servers)
	sort.Slice(sorted, func(i, j int) bool {
		return sorted[i].Name < sorted[j].Name
	})

	for i, s := range sorted {
		if i > 0 {
			buf.WriteString("\n")
		}

		var descParts []string
		if s.Description != "" {
			descParts = append(descParts, safeSSHConfigField(s.Description))
		}
		if len(s.Tags) > 0 {
			tags := make([]string, len(s.Tags))
			for i, tag := range s.Tags {
				tags[i] = safeSSHConfigField(tag)
			}
			descParts = append(descParts, fmt.Sprintf("tags: %s", strings.Join(tags, ",")))
		}
		if len(s.Labels) > 0 && s.FormatLabels() != "-" {
			descParts = append(descParts, fmt.Sprintf("labels: %s", safeSSHConfigField(s.FormatLabels())))
		}
		if len(descParts) > 0 {
			buf.WriteString(fmt.Sprintf("# %s\n", safeSSHConfigField(strings.Join(descParts, " | "))))
		}

		name := safeSSHConfigField(s.Name)
		host := safeSSHConfigField(s.Host)
		user := safeSSHConfigField(s.User)
		if user == "" {
			user = "root"
		}
		port := s.Port
		if port <= 0 {
			port = 22
		}

		buf.WriteString(fmt.Sprintf("Host %s\n", name))
		buf.WriteString(fmt.Sprintf("    HostName %s\n", host))
		buf.WriteString(fmt.Sprintf("    User %s\n", user))
		if port != 22 {
			buf.WriteString(fmt.Sprintf("    Port %d\n", port))
		}

		// Reuse an authenticated session for repeated connections to the same
		// machine. Omitted entirely when the socket directory is not ready, so
		// the exported config never points ssh at a path it cannot bind.
		for _, line := range ControlMasterConfigLines() {
			buf.WriteString(line + "\n")
		}

		switch {
		case secret.Is1PRef(s.KeyPath):
			// ssh(1) cannot read op:// references, and the runtime no longer
			// resolves them either. Leave a pointer instead of a config that
			// silently fails to authenticate.
			buf.WriteString("# no local key configured; run 'ops 1p restore " + s.Name + "' if it is backed up\n")
		case s.KeyPath != "":
			buf.WriteString(fmt.Sprintf("    IdentityFile %s\n", safeSSHConfigField(s.KeyPath)))
			buf.WriteString("    IdentitiesOnly yes\n")
		case s.Password != "":
			buf.WriteString("    PubkeyAuthentication no\n")
			buf.WriteString("    PreferredAuthentications password,keyboard-interactive\n")
		}

		if s.JumpHost != "" {
			buf.WriteString(fmt.Sprintf("    ProxyJump %s\n", safeSSHConfigField(s.JumpHost)))
		}
	}

	buf.WriteString(MarkerEnd + "\n")
	return buf.String()
}

// safeSSHConfigField is a defense-in-depth guard for callers that render
// inventory entries without first calling Server.Validate. Replacing line
// terminators prevents a metadata field from becoming a new ssh_config
// directive; validation remains the primary boundary and rejects these values.
func safeSSHConfigField(value string) string {
	return strings.Map(func(r rune) rune {
		if r < 0x20 || r == 0x7f {
			return ' '
		}
		return r
	}, value)
}

// UpdateSSHConfigFile idempotently inserts or updates the OpsPulse managed block in the given SSH config file.
// If filePath is empty, the default path ~/.ssh/config is used.
func UpdateSSHConfigFile(filePath string, servers []Server) (string, int, error) {
	if filePath == "" {
		var err error
		filePath, err = DefaultSSHConfigPath()
		if err != nil {
			return "", 0, err
		}
	} else {
		filePath = config.ExpandPath(filePath)
	}

	// Prepare the multiplexing directory before rendering, so the block we are
	// about to write carries ControlMaster lines the system ssh can actually
	// use. A failure here is not fatal: the renderer then leaves the lines out.
	_ = EnsureControlMasterDir()

	block := RenderSSHConfig(servers)

	dir := filepath.Dir(filePath)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", 0, fmt.Errorf("create ssh directory %s: %w", dir, err)
	}

	var existingContent string
	if data, readErr := os.ReadFile(filepath.Clean(filePath)); readErr == nil {
		existingContent = string(data)
	} else if !os.IsNotExist(readErr) {
		return "", 0, fmt.Errorf("read existing ssh config %s: %w", filePath, readErr)
	}
	if err := ValidateSSHConfigUpdate(existingContent); err != nil {
		return "", 0, fmt.Errorf("refusing to update %s: %w", filePath, err)
	}

	newContent := MergeSSHConfigContent(existingContent, block)

	// Write atomically via temporary file in the same directory
	tempFile, err := os.CreateTemp(dir, "ssh_config.*.tmp")
	if err != nil {
		return "", 0, fmt.Errorf("create temp ssh config file: %w", err)
	}
	tempPath := tempFile.Name()
	defer func() {
		_ = tempFile.Close()
		_ = os.Remove(tempPath)
	}()

	if _, err := tempFile.WriteString(newContent); err != nil {
		return "", 0, fmt.Errorf("write temp ssh config: %w", err)
	}
	if err := tempFile.Close(); err != nil {
		return "", 0, fmt.Errorf("close temp ssh config: %w", err)
	}

	_ = os.Chmod(tempPath, 0o600)

	if err := os.Rename(tempPath, filePath); err != nil {
		// Fallback for Windows file rename when destination file exists
		backupPath := fmt.Sprintf("%s.bak.%d", filePath, time.Now().UnixNano())
		if renameBackupErr := os.Rename(filePath, backupPath); renameBackupErr == nil {
			if retryErr := os.Rename(tempPath, filePath); retryErr != nil {
				_ = os.Rename(backupPath, filePath) // restore original on failure
				return "", 0, fmt.Errorf("replace ssh config %s: %w", filePath, retryErr)
			}
			_ = os.Remove(backupPath)
		} else {
			// If moving to backupPath fails, do NOT remove filePath to prevent permanent data loss.
			return "", 0, fmt.Errorf("backup existing ssh config %s before replacing: %w", filePath, renameBackupErr)
		}
	}
	_ = os.Chmod(filePath, 0o600)

	return newContent, len(servers), nil
}

// MergeSSHConfigContent replaces the managed block if present, or appends it cleanly.
func MergeSSHConfigContent(existing, block string) string {
	normExisting := strings.ReplaceAll(existing, "\r\n", "\n")
	normBlock := strings.ReplaceAll(block, "\r\n", "\n")

	beginIdx := strings.Index(normExisting, MarkerBegin)
	endIdx := strings.Index(normExisting, MarkerEnd)

	if beginIdx != -1 && endIdx != -1 && endIdx >= beginIdx {
		postEnd := endIdx + len(MarkerEnd)
		if postEnd < len(normExisting) && normExisting[postEnd] == '\n' {
			postEnd++
		}

		prefix := normExisting[:beginIdx]
		suffix := normExisting[postEnd:]
		return prefix + normBlock + suffix
	}

	trimmed := strings.TrimRight(normExisting, "\n")
	if trimmed == "" {
		return normBlock
	}
	return trimmed + "\n\n" + normBlock
}

// ValidateSSHConfigUpdate checks the one structural failure MergeSSHConfigContent
// cannot recover from: a managed marker that appears more than once, or an end
// marker without a matching begin marker.
//
// Replacing only the first block in a file with duplicated markers would leave
// stale managed Host entries behind, which is precisely the kind of partial
// rewrite this command must not do.
func ValidateSSHConfigUpdate(existing string) error {
	norm := strings.ReplaceAll(existing, "\r\n", "\n")
	begins := strings.Count(norm, MarkerBegin)
	ends := strings.Count(norm, MarkerEnd)
	switch {
	case begins == 0 && ends == 0:
		return nil
	case begins == 1 && ends == 1:
		if strings.Index(norm, MarkerBegin) > strings.Index(norm, MarkerEnd) {
			return fmt.Errorf("managed SSH config markers are out of order; refusing to rewrite %s", "the file")
		}
		return nil
	default:
		return fmt.Errorf("managed SSH config markers are inconsistent (begin=%d, end=%d); fix the markers by hand before running setup", begins, ends)
	}
}

// HasManagedSSHBlock reports whether content carries exactly one complete
// managed block.
func HasManagedSSHBlock(content string) bool {
	return ValidateSSHConfigUpdate(content) == nil &&
		strings.Count(strings.ReplaceAll(content, "\r\n", "\n"), MarkerBegin) == 1
}
